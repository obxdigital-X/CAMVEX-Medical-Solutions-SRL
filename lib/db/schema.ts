// Audit trail ("Caché"). One row per meaningful change made by a panel user
// (create/update/delete across catalog, sheets, quotations, messages, users,
// site content). Read-only from the UI and visible to admins only.
export const activityLog = pgTable("activity_log", {
  id: serial("id").primaryKey(),
  actorId: text("actorId").notNull().default(""),
  actorName: text("actorName").notNull().default(""),
  actorUsername: text("actorUsername").notNull().default(""),
  actorRole: text("actorRole").notNull().default(""),
  action: text("action").notNull().default(""), // created | updated | deleted
  entity: text("entity").notNull().default(""), // module label, e.g. "Catálogo"
  summary: text("summary").notNull().default(""),
  createdAt: timestamp("createdAt").notNull().defaultNow(),
})
