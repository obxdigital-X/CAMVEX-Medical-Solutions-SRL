// Technical data sheets ("fichas técnicas") built from a fixed CAMVEX template.
// All sheets share the same layout; the dynamic fields below vary per product.
// JSON-encoded columns: characteristics = string[], applications = string[],
// specs = { param: string; value: string }[].
export const dataSheet = pgTable("data_sheet", {
  id: serial("id").primaryKey(),
  title: text("title").notNull().default(""),
  subtitle: text("subtitle").notNull().default(""),
  intro: text("intro").notNull().default(""),
  image: text("image").notNull().default(""),
  formula: text("formula").notNull().default(""),
  manufacturer: text("manufacturer").notNull().default(""),
  presentation: text("presentation").notNull().default(""),
  characteristics: text("characteristics").notNull().default("[]"),
  specs: text("specs").notNull().default("[]"),
  applications: text("applications").notNull().default("[]"),
  createdAt: timestamp("createdAt").notNull().defaultNow(),
  updatedAt: timestamp("updatedAt").notNull().defaultNow(),
})

// Price quotations ("cotizaciones") built from a fixed CAMVEX template. Each
// quotation targets a client/company and lists line items. Money is computed
// from the items at render time; only inputs are stored. JSON-encoded column:
// items = { description: string; image: string; quantity: number; unitPrice: number }[].
export const quotation = pgTable("quotation", {
  id: serial("id").primaryKey(),
  number: text("number").notNull().default(""),
  clientName: text("clientName").notNull().default(""),
  clientContact: text("clientContact").notNull().default(""),
  clientEmail: text("clientEmail").notNull().default(""),
  clientPhone: text("clientPhone").notNull().default(""),
  title: text("title").notNull().default(""),
  // Who prepared the quotation (CAMVEX rep) + their contact info.
  preparedBy: text("preparedBy").notNull().default(""),
  preparedByContact: text("preparedByContact").notNull().default(""),
  currency: text("currency").notNull().default("DOP"), // DOP | USD
  taxEnabled: boolean("taxEnabled").notNull().default(true),
  taxRate: text("taxRate").notNull().default("18"),
  validityDays: integer("validityDays").notNull().default(15),
  notes: text("notes").notNull().default(""),
  items: text("items").notNull().default("[]"),
  createdAt: timestamp("createdAt").notNull().defaultNow(),
  updatedAt: timestamp("updatedAt").notNull().defaultNow(),
})

// Strategic-alliance logos shown in the home-page ticker. Admin-managed:
